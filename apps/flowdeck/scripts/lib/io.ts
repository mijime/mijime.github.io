import { writeFileSync } from "node:fs";
import type { RunRow } from "./aggregate";
import { distribution, median, rate } from "./stats";
import type { RunResult } from "./runner";
import type { AiProfile } from "../../src/engine/types";

export function writeOutput(content: string, out: string | null): void {
  if (out) {
    writeFileSync(out, content);
    console.log(`wrote ${out}`);
    return;
  }
  process.stdout.write(content.endsWith("\n") ? content : `${content}\n`);
}

function csvCell(value: string | number | boolean): string {
  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

export function rowsToCsv(rows: RunRow[]): string {
  if (rows.length === 0) return "";
  const headers = Object.keys(rows[0]!) as (keyof RunRow)[];
  const lines = [headers.join(",")];
  for (const row of rows) {
    lines.push(headers.map((header) => csvCell(row[header])).join(","));
  }
  return `${lines.join("\n")}\n`;
}

export function jsonReport(results: RunResult[], rows: RunRow[]): string {
  const scores = rows.map((row) => row.finalScore);
  return JSON.stringify(
    {
      meta: {
        runs: rows.length,
        scenario: results[0]?.scenario ?? "base",
        days: results[0]?.days ?? 0,
        players: results[0]?.playerCount ?? 0,
      },
      summary: {
        score: distribution(scores),
        stars: [0, 1, 2, 3].map((stars) =>
          rate(rows.filter((row) => row.stars === stars).length, rows.length),
        ),
        failRate: rate(rows.filter((row) => row.failed).length, rows.length),
        debt: median(rows.map((row) => row.debt)),
        completed: median(rows.map((row) => row.completed)),
        expired: median(rows.map((row) => row.expired)),
      },
      rows,
    },
    null,
    2,
  );
}

export interface BenchmarkEntry {
  players: number;
  days: number;
  swing: number;
  aiProfile: AiProfile;
  runs: number;
  score: { p10: number; p25: number; median: number; p75: number; p90: number; mean: number };
  stars: number[];
  failRate: number;
  debt: number;
  completed: number;
  expired: number;
  avgWip: number;
  avgLeadTime: number;
  riskDebt: number;
}

export function benchmarkEntry(
  results: RunResult[],
  players: number,
  days: number,
  swing: number,
  aiProfile: AiProfile,
): BenchmarkEntry {
  const rows = results.map((result) => result.state.outcome).filter((outcome) => outcome !== null);
  const scores = rows.map((outcome) => outcome.finalScore);
  const stats = distribution(scores);
  const total = Math.max(1, rows.length);
  return {
    players,
    days,
    swing,
    aiProfile,
    runs: rows.length,
    score: {
      p10: stats.p10,
      p25: stats.p25,
      median: stats.median,
      p75: stats.p75,
      p90: stats.p90,
      mean: Number(stats.mean.toFixed(2)),
    },
    stars: [0, 1, 2, 3].map((stars) =>
      Number(rate(rows.filter((outcome) => outcome.stars === stars).length, total).toFixed(4)),
    ),
    failRate: Number(rate(rows.filter((outcome) => outcome.failed).length, total).toFixed(4)),
    debt: median(rows.map((outcome) => outcome.teamDebt)),
    completed: median(rows.map((outcome) => outcome.completed)),
    expired: median(rows.map((outcome) => outcome.expired)),
    avgWip: Number((rows.reduce((sum, outcome) => sum + outcome.avgWip, 0) / total).toFixed(2)),
    avgLeadTime: Number(
      (rows.reduce((sum, outcome) => sum + outcome.avgLeadTime, 0) / total).toFixed(2),
    ),
    riskDebt: Number(
      (
        results.reduce(
          (sum, result) =>
            sum +
            Object.values(result.state.riskStats).reduce((inner, stat) => inner + stat.debt, 0),
          0,
        ) / total
      ).toFixed(2),
    ),
  };
}

export function benchmarkJson(entries: BenchmarkEntry[]): string {
  return `${JSON.stringify(
    {
      version: 3,
      note: "Generated by pnpm --filter @mijime/flowdeck benchmark. All players are bots. Keys are players x days x generationSwing x standard. Long games (100 days) use up to 200 seeds.",
      configs: Object.fromEntries(
        entries.map((entry) => [
          `${entry.players}x${entry.days}x${entry.swing.toFixed(1)}x${entry.aiProfile}`,
          entry,
        ]),
      ),
    },
    null,
    2,
  )}\n`;
}
