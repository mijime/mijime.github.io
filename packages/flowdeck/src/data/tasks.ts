import type { CardEffect, TaskDef, TaskPenalty, TaskReward } from "../engine/types";

const r = (type: TaskReward["type"], level: number, effect?: CardEffect): TaskReward => ({
  type,
  level,
  effect,
});

function task(
  id: string,
  title: string,
  design: number,
  dev: number,
  test: number,
  score: number,
  deadline: number,
  reward: TaskReward,
): TaskDef {
  return {
    id,
    title,
    requirements: { design, dev, test },
    score,
    deadline: deadline + 1,
    reward,
  };
}

function incident(
  id: string,
  title: string,
  design: number,
  dev: number,
  test: number,
  score: number,
  deadline: number,
  reward: TaskReward,
  penalty: TaskPenalty = { kind: "allPlayersDebt", amount: 2 },
): TaskDef {
  return {
    ...task(id, title, design, dev, test, score, deadline, reward),
    kind: "incident",
    penalty,
  };
}

